document.addEventListener("DOMContentLoaded", function() {
    const metrics = document.querySelectorAll('.metric-num');
    
    // Store original text and prep for animation
    metrics.forEach(metric => {
        const text = metric.innerText.trim();
        const numMatch = text.match(/\d+/);
        if (numMatch) {
            metric.dataset.target = numMatch[0];
            metric.dataset.suffix = text.replace(numMatch[0], '');
            metric.innerText = '0' + metric.dataset.suffix;
        }
    });

    const observer = new IntersectionObserver((entries, observer) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                const el = entry.target;
                const target = parseInt(el.dataset.target, 10);
                const suffix = el.dataset.suffix || '';
                if (!isNaN(target)) {
                    let current = 0;
                    const duration = 1500; // 1.5 seconds
                    const interval = 30;
                    const step = target / (duration / interval);
                    
                    const timer = setInterval(() => {
                        current += step;
                        if (current >= target) {
                            el.innerText = target + suffix;
                            clearInterval(timer);
                        } else {
                            el.innerText = Math.ceil(current) + suffix;
                        }
                    }, interval);
                }
                observer.unobserve(el);
            }
        });
    }, { threshold: 0.3 });

    metrics.forEach(metric => {
        if (metric.dataset.target) {
            observer.observe(metric);
        }
    });
});
</script>

